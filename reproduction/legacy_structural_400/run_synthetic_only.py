def synthetic_population(rep: int, split: int, n: int, agreement: float) -> list[dict]:
    r=rng_for(210,rep,split)
    modal=r.integers(0,3,n);error=(r.random(n)<CFG['synthetic_signal_control']['error_probability']).astype(int)
    u=rng_for(211,rep,split).random(n)
    signal=np.where(u<agreement,error,1-error)
    noise=rng_for(212,rep,split).integers(0,2,n)
    ids=rng_for(213,rep,split).permutation(n)
    templates=rng_for(214,rep,split).integers(0,4,n)
    return [{'modal':int(modal[i]),'error':int(error[i]),'signal':int(signal[i]),'noise':int(noise[i]),
             'id':f'{split}:{int(ids[i])}','template':int(templates[i])} for i in range(n)]


def learner_keys(rows: list[dict], policy: str) -> list:
    if policy=='modal_only':return [(r['modal'],) for r in rows]
    field={'modal_iid_bit':'noise','modal_signal':'signal','modal_unique_id':'id'}[policy]
    return [(r['modal'],r[field]) for r in rows]


def fitted_scores(train: list[dict], other: list[dict], policy: str) -> list[F]:
    cells=defaultdict(lambda:[0,0]);baseline=defaultdict(lambda:[0,0])
    for key,row in zip(learner_keys(train,policy),train):
        cells[key][0]+=1;cells[key][1]+=row['error'];baseline[row['modal']][0]+=1;baseline[row['modal']][1]+=row['error']
    out=[]
    for key,row in zip(learner_keys(other,policy),other):
        n,e=cells[key] if key in cells else baseline[row['modal']]
        out.append(F(e+1,n+2))
    return out


def calibration_threshold(scores: list[F], errors: list[int], alpha: F) -> tuple[F|None,int,int]:
    d=defaultdict(lambda:[0,0])
    for s,e in zip(scores,errors):d[s][0]+=1;d[s][1]+=int(e)
    n=e=0;best=(None,0,0)
    for s,(nn,ee) in sorted(d.items()):
        n+=nn;e+=ee
        if F(e,n)<=alpha:best=(s,n,e)
    return best


def signal_controls(out: Path) -> None:
    sc=CFG['synthetic_signal_control'];results=[];hashes=[]
    for rep in range(sc['repeats']):
      for agreement in sc['signal_agreement']:
        train=synthetic_population(rep,0,sc['train_n'],agreement)
        cal=synthetic_population(rep,1,sc['calibration_n'],agreement)
        test=synthetic_population(rep,2,sc['test_n'],agreement)
        assert not ({r['id'] for r in train}&{r['id'] for r in cal}) and not ({r['id'] for r in train}&{r['id'] for r in test})
        hashes.append({'replicate':rep,'agreement':agreement,**{name+'_sha256':hashlib.sha256(json.dumps(data,sort_keys=True).encode()).hexdigest() for name,data in [('train',train),('calibration',cal),('test',test)]}})
        for policy in sc['policies']:
            keys=learner_keys(train,policy);bl=partition(keys,[r['error'] for r in train]);oracle_train=solve(oracle_signature(bl),F(1,20))
            scores=fitted_scores(train,cal,policy);t,ca,ce=calibration_threshold(scores,[r['error'] for r in cal],F(1,20))
            # The fixed threshold is applied once to independent test, without test-label adaptation.
            testscores=fitted_scores(train,test,policy)
            selected=[i for i,s in enumerate(testscores) if t is not None and s<=t]
            te=sum(test[i]['error'] for i in selected);ta=len(selected)
            results.append({'replicate':rep,'signal_agreement':agreement,'policy':policy,
                            'train_n':len(train),'train_errors':sum(r['error'] for r in train),
                            'train_oracle_coverage':float(oracle_train.coverage),
                            'calibration_n':len(cal),'calibration_accepted':ca,'calibration_errors':ce,
                            'calibration_risk':ce/ca if ca else None,'threshold_fraction':str(t) if t is not None else '',
                            'test_n':len(test),'test_total_errors':sum(r['error'] for r in test),'test_accepted':ta,'test_errors':te,
                            'test_coverage':ta/len(test),'test_risk':te/ta if ta else None,
                            'test_target_50pct_5pct':bool(ta*2>=len(test) and te*20<=ta),
                            'test_nonempty':bool(ta),'test_low_risk_nonempty':bool(ta and te*20<=ta)})
        INVARIANTS['independent_synthetic_splits']+=1
    write_csv(out/'synthetic_signal_controls.csv',results);write_csv(out/'synthetic_signal_data_hashes.csv',hashes)
    d=pd.DataFrame(results)
    summary=d.groupby(['signal_agreement','policy']).agg(
        repeats=('replicate','size'),train_oracle_mean=('train_oracle_coverage','mean'),
        test_coverage_mean=('test_coverage','mean'),test_coverage_sd=('test_coverage','std'),
        test_nonempty_replicates=('test_nonempty','sum'),test_risk_nonempty_mean=('test_risk','mean'),
        test_risk_nonempty_sd=('test_risk','std'),test_accepted_total=('test_accepted','sum'),test_errors_total=('test_errors','sum'),
        test_target_met_replicates=('test_target_50pct_5pct','sum'),test_target_met_rate=('test_target_50pct_5pct','mean')).reset_index()
    summary['test_pooled_risk']=summary.test_errors_total/summary.test_accepted_total.replace(0,np.nan)
    summary.to_csv(out/'synthetic_signal_summary.csv',index=False,encoding='utf-8-sig')
    print(f'Synthetic signal controls: {len(results)} evaluated gates',flush=True)


