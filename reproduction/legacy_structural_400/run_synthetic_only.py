def keys_for(rows: list[dict], representation: str, noise: np.ndarray | None = None) -> list[Any]:
    if representation=='stored_H': return [F(str(r['H_saved'])) for r in rows]
    if representation=='exact_H': return [r['_H_key'] for r in rows]
    if representation=='H_modal': return [(F(str(r['H_saved'])),r['saved_modal']) for r in rows]
    if representation=='counts_modal': return [(r['_counts'],r['saved_modal']) for r in rows]
    if representation=='seq_modal': return [(r['_S'],r['saved_modal']) for r in rows]
    if representation in ['seq_unique_ID','seq_noise']:
        assert noise is not None and len(noise)==len(rows)
        return [(r['_S'],r['saved_modal'],int(noise[i])) for i,r in enumerate(rows)]
    raise ValueError(representation)


def partition(keys: Iterable, errors: Iterable[int]) -> list[dict]:
    acc: dict[Any, list] = {}
    for i,(k,e) in enumerate(zip(keys,errors)):
        if k not in acc: acc[k]=[0,0,[]]
        acc[k][0]+=1;acc[k][1]+=int(e);acc[k][2].append(i)
    return [{'key':k,'n':v[0],'e':v[1],'members':v[2]} for k,v in sorted(acc.items(),key=lambda kv:repr(kv[0]))]


def oracle_signature(blocks: list[dict]) -> tuple[tuple[F,int],...]:
    d: dict[F,int] = defaultdict(int)
    for b in blocks:
        n,e=int(b['n']),int(b['e']);assert n>0 and 0<=e<=n
        d[F(e,n)]+=n
    return tuple(sorted(d.items()))


@dataclass(frozen=True)
class Solution:
    coverage: F
    risk: F | None
    dual_lambda: F
    dual_coverage: F
    q_by_risk: tuple[F,...]


@lru_cache(maxsize=250000)
def solve(signature: tuple[tuple[F,int],...], alpha: F) -> Solution:
    """Fractional knapsack in ascending block error rate; verify weak-dual equality."""
    global CERT_CHECKS
    n=sum(m for _,m in signature); assert n>0 and 0<=alpha<1
    mean=sum((r*m for r,m in signature),F(0))/n
    if mean<=alpha:
        q=tuple(F(1) for _ in signature);lam=F(0)
    else:
        budget=F(0); qs=[];lam=None; exhausted=False
        for r,m in signature:
            if exhausted: qi=F(0)
            elif r<=alpha:
                qi=F(1);budget+=(alpha-r)*m
            else:
                take=min(F(m),budget/(r-alpha));qi=take/m
                budget-=(r-alpha)*take
                if take<m:
                    lam=1/(r-alpha);exhausted=True
            qs.append(qi)
        assert lam is not None
        q=tuple(qs)
    accepted=sum((m*qi for (_,m),qi in zip(signature,q)),F(0))
    errors=sum((r*m*qi for (r,m),qi in zip(signature,q)),F(0))
    assert all(0<=qi<=1 for qi in q) and errors<=alpha*accepted
    dual=sum((max(F(0),F(m)-lam*(r-alpha)*m) for r,m in signature),F(0))/n
    cov=accepted/n;assert cov==dual
    CERT_CHECKS+=1
    return Solution(cov,errors/accepted if accepted else None,lam,dual,q)


def oracle(blocks: list[dict]) -> list[Solution]:
    sig=oracle_signature(blocks)
    return [solve(sig,a) for a in ALPHAS]


def case_blocks(rows: list[dict]) -> list[dict]:
    e=sum(r['error'] for r in rows);n=len(rows)
    return [b for b in [{'n':n-e,'e':0},{'n':e,'e':e}] if b['n']]


def statistics(blocks: list[dict]) -> dict:
    n=sum(b['n'] for b in blocks)
    return dict(n=n,blocks=len(blocks),duplicate_blocks=sum(b['n']>1 for b in blocks),
                singleton_units=sum(b['n'] for b in blocks if b['n']==1),
                singleton_fraction=sum(b['n'] for b in blocks if b['n']==1)/n,
                mixed_blocks=sum(0<b['e']<b['n'] for b in blocks),
                mixed_units=sum(b['n'] for b in blocks if 0<b['e']<b['n']),
                equality_constraints=sum(b['n']-1 for b in blocks))


def relax(full: list[dict], retain: set[int], rows: list[dict]) -> list[dict]:
    result=[]
    for j,b in enumerate(full):
        if j in retain: result.append(b)
        else:
            result.extend({'n':1,'e':rows[i]['error']} for i in b['members'])
    return result


def cert_record(blocks: list[dict], alpha: F, identity: dict) -> dict:
    sig=oracle_signature(blocks);s=solve(sig,alpha)
    return {**identity,'alpha':str(alpha),'coverage':str(s.coverage),'risk':str(s.risk) if s.risk is not None else None,
            'dual_lambda':str(s.dual_lambda),'dual_coverage':str(s.dual_coverage),
            'risk_groups':[{'risk':str(r),'n':n,'e':int(r*n),'q':str(q)} for (r,n),q in zip(sig,s.q_by_risk)]}


def scipy_check(blocks: list[dict], alphas: Iterable[F], identity: str) -> None:
    from scipy.optimize import linprog
    ns=np.array([b['n'] for b in blocks],float);es=np.array([b['e'] for b in blocks],float)
    for a in alphas:
        r=linprog(-ns/ns.sum(),A_ub=[es-float(a)*ns],b_ub=[0.0],bounds=(0,1),method='highs')
        s=solve(oracle_signature(blocks),a)
        assert r.success,(identity,a,r.message)
        diff=abs(-r.fun-float(s.coverage));assert diff<1e-8,(identity,a,diff)
        SOLVER_CHECKS.append({'identity':identity,'alpha':str(a),'fraction_value':str(s.coverage),'scipy_value':-r.fun,'abs_difference':diff})


def evaluation_rows(upper: list[Solution], full: list[Solution], case: list[Solution], lower: list[Solution],
                    meta: dict, full_enumeration: bool=False) -> list[dict]:
    out=[]
    for a,u,t,c,l in zip(ALPHAS,upper,full,case,lower):
        assert l.coverage<=t.coverage<=u.coverage<=c.coverage
        INVARIANTS['ordered_bounds_checks']+=1
        denom=[v for v in CGRID if t.coverage<v<=c.coverage]
        detected=sum(u.coverage<v for v in denom)
        false_excl=sum(v>u.coverage and v<=t.coverage for v in CGRID)
        assert false_excl==0
        witness=sum(v<=l.coverage for v in CGRID)
        excluded=sum(v>u.coverage for v in CGRID)
        unresolved=len(CGRID)-witness-excluded
        feasible_complete=sum(v<=t.coverage for v in CGRID) if full_enumeration else witness
        unresolved_audit=len(CGRID)-feasible_complete-excluded
        assert unresolved>=0 and unresolved_audit>=0
        INVARIANTS['requirement_decisions_checked']+=len(CGRID)
        out.append({**meta,'alpha':float(a),'alpha_fraction':str(a),'upper_coverage':float(u.coverage),
                    'upper_fraction':str(u.coverage),'full_coverage':float(t.coverage),'full_fraction':str(t.coverage),
                    'case_coverage':float(c.coverage),'summary_witness_coverage':float(l.coverage),
                    'gap_pp':float(u.coverage-t.coverage)*100,'dual_lambda':str(u.dual_lambda),
                    'grid_n':len(CGRID),'information_excluded_n':len(denom),'additional_detected_n':detected,
                    'additional_detection_rate':detected/len(denom) if denom else None,
                    'base_accuracy_excluded_n':sum(v>c.coverage for v in CGRID),'false_exclusions':false_excl,
                    'summary_witness_feasible_n':witness,'excluded_n':excluded,
                    'unresolved_summary_witness_n':unresolved,'unresolved_after_full_completion_n':unresolved_audit})
    return out


def summarize_partial(rows: list[dict], by_dataset: list[str], by_summary: list[str], out: Path, prefix: str) -> None:
    d=pd.DataFrame(rows)
    ds=d.groupby(by_dataset,dropna=False,sort=False).agg(
        gap_mean_pp=('gap_pp','mean'),gap_max_pp=('gap_pp','max'),
        gap_5pct_pp=('gap_pp',lambda s: np.nan), # filled explicitly below
        information_excluded_n=('information_excluded_n','sum'),
        additional_detected_n=('additional_detected_n','sum'),
        unresolved_summary_n=('unresolved_summary_witness_n','sum'),
        unresolved_completion_n=('unresolved_after_full_completion_n','sum'),
        requirements_n=('grid_n','sum'),false_exclusions=('false_exclusions','sum')).reset_index()
    g5=d[d['alpha']==0.05][by_dataset+['gap_pp','upper_coverage','full_coverage']].rename(columns={'gap_pp':'gap_at_5pct_pp'})
    ds=ds.drop(columns='gap_5pct_pp').merge(g5,on=by_dataset,how='left',validate='one_to_one')
    ds['additional_detection_rate']=ds['additional_detected_n']/ds['information_excluded_n'].replace(0,np.nan)
    ds['unresolved_summary_rate']=ds['unresolved_summary_n']/ds['requirements_n']
    ds['unresolved_completion_rate']=ds['unresolved_completion_n']/ds['requirements_n']
    ds.to_csv(out/f'{prefix}_per_dataset.csv',index=False,encoding='utf-8-sig')
    agg=ds.groupby(by_summary,dropna=False,sort=False).agg(
        datasets=('gap_mean_pp','size'),gap_mean_pp=('gap_mean_pp','mean'),
        gap_sd_pp=('gap_mean_pp','std'),gap_min_pp=('gap_mean_pp','min'),gap_max_pp=('gap_mean_pp','max'),
        gap_at_5pct_mean_pp=('gap_at_5pct_pp','mean'),
        detection_macro_mean=('additional_detection_rate','mean'),
        detection_macro_sd=('additional_detection_rate','std'),
        detection_valid_datasets=('additional_detection_rate','count'),
        information_excluded_n=('information_excluded_n','sum'),additional_detected_n=('additional_detected_n','sum'),
        unresolved_summary_mean=('unresolved_summary_rate','mean'),
        unresolved_completion_mean=('unresolved_completion_rate','mean'),
        false_exclusions=('false_exclusions','sum')).reset_index()
    agg['detection_micro']=agg.additional_detected_n/agg.information_excluded_n.replace(0,np.nan)
    agg.to_csv(out/f'{prefix}_summary.csv',index=False,encoding='utf-8-sig')


def clinical_partial(rows: list[dict], out: Path) -> None:
    results=[]; catalogue=[];certs=[]
    for model in CFG['clinical']['models']:
      for scope in CFG['clinical']['scopes']:
        rs=[r for r in rows if r['model']==model and (scope=='all_GT' or r['GT'] in ('PDAC','NET'))]
        full=partition(keys_for(rs,'seq_modal'),[r['error'] for r in rs])
        fc=oracle(full);cc=oracle(case_blocks(rs));low=oracle(partition(keys_for(rs,'H_modal'),[r['error'] for r in rs]))
        dup=[i for i,b in enumerate(full) if b['n']>1];assert len(dup)==3
        for k,j in enumerate(dup):
            b=full[j]; s=rs[b['members'][0]]['_S'];unanimity=len(set(s))==1
            label=f'{s[0]}x20' if unanimity else 'nonunanimous_duplicate'
            catalogue.append({'model':model,'scope':scope,'bit':k,'block_index':j,'name':label,'n':b['n'],'e':b['e'],'unanimity':unanimity,'uids':'|'.join(rs[i]['uid'] for i in b['members'])})
        cached={}
        for mask in range(1<<len(dup)):
            retain={j for k,j in enumerate(dup) if mask&(1<<k)}
            bl=relax(full,retain,rs);upper=oracle(bl);cached[mask]=upper
            names=[r['name'] for r in catalogue if r['model']==model and r['scope']==scope and (mask&(1<<r['bit']))]
            meta={'model':model,'scope':scope,'n':len(rs),'mask':mask,'retained':'|'.join(names) or 'none',
                  'disclosed_blocks':len(retain),'disclosed_units':sum(full[j]['n'] for j in retain),
                  'disclosed_equalities':sum(full[j]['n']-1 for j in retain),
                  'total_equalities':sum(b['n']-1 for b in full)}
            results.extend(evaluation_rows(upper,fc,cc,low,meta,len(retain)==len(dup)))
            scipy_check(bl,ALPHAS,f'clinical/{model}/{scope}/{mask}')
            certs.append(cert_record(bl,F(1,20),meta))
        for a in cached:
          for b in cached:
            if a!=b and (a&b)==a:
              assert all(x.coverage>=y.coverage for x,y in zip(cached[a],cached[b]))
              INVARIANTS['nested_evidence_comparisons']+=len(ALPHAS)
    write_csv(out/'clinical_partial_evidence.csv',results);write_csv(out/'clinical_duplicate_blocks.csv',catalogue)
    (out/'clinical_partial_certificates.json').write_text(json.dumps(certs,ensure_ascii=False,indent=2),encoding='utf8')
    summarize_partial(results,['model','scope','n','mask','retained','disclosed_blocks','disclosed_units','disclosed_equalities','total_equalities'],['model','scope','mask','retained'],out,'clinical_partial')
    print(f'Clinical partial evidence: {len(results)} alpha-wise rows',flush=True)


def representation_experiments(rows: list[dict], out: Path) -> None:
    results=[];thresh=[];assignments=[];certs=[]
    N=len(rows);base_unique=rng_for(31,0).permutation(N)
    allnoise={}
    for card in CFG['clinical']['noise_cardinalities']:
      for rep in range(CFG['clinical']['noise_seeds']):
        z=rng_for(32,card,rep).integers(0,card,N);allnoise[(card,rep)]=z
        assignments.extend({'uid':r['uid'],'cardinality':card,'replicate':rep,'token':int(z[i])} for i,r in enumerate(rows))
    assignments.extend({'uid':r['uid'],'cardinality':'unique','replicate':0,'token':int(base_unique[i])} for i,r in enumerate(rows))
    for model in CFG['clinical']['models']:
      for scope in CFG['clinical']['scopes']:
        ids=[i for i,r in enumerate(rows) if r['model']==model and (scope=='all_GT' or r['GT'] in ['PDAC','NET'])]
        rs=[rows[i] for i in ids];errors=[r['error'] for r in rs]
        base=oracle(partition(keys_for(rs,'seq_modal'),errors));case=oracle(case_blocks(rs))
        reps=[(name,0,0,None) for name in ['stored_H','exact_H','H_modal','counts_modal','seq_modal']]
        reps.append(('seq_unique_ID',0,len(rs),base_unique[ids]))
        reps.extend(('seq_noise',rep,card,z[ids]) for (card,rep),z in allnoise.items())
        curve_by_rep={}
        for name,rep,card,z in reps:
            blocks=partition(keys_for(rs,name,z),errors);curve=oracle(blocks);st=statistics(blocks)
            for a,s,b,c in zip(ALPHAS,curve,base,case):
                if name in ('seq_noise','seq_unique_ID'):assert b.coverage<=s.coverage<=c.coverage
                if name=='seq_unique_ID':assert s.coverage==c.coverage
                results.append({'model':model,'scope':scope,'representation':name,'replicate':rep,'cardinality':card,
                                **st,'alpha':float(a),'coverage':float(s.coverage),'coverage_fraction':str(s.coverage),
                                'sequence_reference':float(b.coverage),'case_reference':float(c.coverage),
                                'gain_vs_sequence_pp':100*float(s.coverage-b.coverage),'dual_lambda':str(s.dual_lambda)})
                INVARIANTS['representation_bounds_checks']+=1
            if name!='seq_noise':curve_by_rep[name]=curve
            if name!='seq_noise' or rep==0:certs.append(cert_record(blocks,F(1,20),{'model':model,'scope':scope,'representation':name,'replicate':rep,'cardinality':card}))
        chain=['stored_H','exact_H','counts_modal','seq_modal','seq_unique_ID']
        for a,b in zip(chain[:-1],chain[1:]):
            assert all(x.coverage<=y.coverage for x,y in zip(curve_by_rep[a],curve_by_rep[b]))
        assert all(x.coverage<=y.coverage for x,y in zip(curve_by_rep['stored_H'],curve_by_rep['H_modal']))
        assert all(x.coverage<=y.coverage for x,y in zip(curve_by_rep['H_modal'],curve_by_rep['counts_modal']))
        thresholds=sorted({F(str(r['H_saved'])) for r in rs})
        thresholds_data=[]
        for t in thresholds:
            selected=[r for r in rs if F(str(r['H_saved']))<=t];e=sum(r['error'] for r in selected);nn=len(selected)
            d={'model':model,'scope':scope,'threshold':float(t),'accepted':nn,'errors':e,'coverage':nn/len(rs),'risk':e/nn}
            thresholds_data.append((F(nn,len(rs)),F(e,nn)));thresh.append(d)
        for a in ALPHAS:
            opt=max((c for c,risk in thresholds_data if risk<=a),default=F(0))
            assert opt<=curve_by_rep['stored_H'][ALPHAS.index(a)].coverage
            results.append({'model':model,'scope':scope,'representation':'lowH_threshold','replicate':0,'cardinality':0,
                            'n':len(rs),'alpha':float(a),'coverage':float(opt),'coverage_fraction':str(opt),
                            'sequence_reference':float(base[ALPHAS.index(a)].coverage),'case_reference':float(case[ALPHAS.index(a)].coverage)})
    write_csv(out/'representation_controls.csv',results);write_csv(out/'lowH_threshold_observations.csv',thresh)
    write_csv(out/'clinical_noise_assignments.csv',assignments)
    (out/'representation_certificates.json').write_text(json.dumps(certs,ensure_ascii=False,indent=2),encoding='utf8')
    d=pd.DataFrame(results);d[d.alpha==0.05].to_csv(out/'representations_at_5pct.csv',index=False,encoding='utf-8-sig')
    noise=d[(d.alpha==0.05)&(d.representation=='seq_noise')]
    summ=noise.groupby(['model','scope','cardinality']).agg(repeats=('coverage','size'),coverage_mean=('coverage','mean'),coverage_sd=('coverage','std'),coverage_min=('coverage','min'),coverage_max=('coverage','max'),coverage_q05=('coverage',lambda s:s.quantile(.05)),coverage_q95=('coverage',lambda s:s.quantile(.95)),gain_mean_pp=('gain_vs_sequence_pp','mean'),singleton_mean=('singleton_fraction','mean')).reset_index()
    summ.to_csv(out/'noise_controls_summary_5pct.csv',index=False,encoding='utf-8-sig')
    print(f'Clinical representation controls: {len(results)} alpha-wise rows',flush=True)


def paired_base(n: int, rep: int) -> tuple[np.ndarray,np.ndarray,np.ndarray]:
    rr=rng_for(100,n,rep)
    modes=np.arange(n)%3;err=np.zeros(n,dtype=int)
    counts=np.bincount(modes,minlength=3);E=round(n*CFG['synthetic']['error_fraction'])
    quotas=counts*E/n;qe=np.floor(quotas).astype(int)
    for k in np.argsort(-(quotas-qe),kind='stable')[:E-int(qe.sum())]:qe[k]+=1
    for m in range(3):
        idx=np.where(modes==m)[0];err[rr.permutation(idx)[:qe[m]]]=1
    gt=(modes+np.where(err,rr.integers(1,3,n),0))%3
    assert err.sum()==E
    return modes,err,gt


def synthetic_dataset(n: int, rep: int, si: int, scenario: str) -> list[dict]:
    modes,err,gt=paired_base(n,rep)
    rp=rng_for(101,n,rep,si);rs=rng_for(102,n,rep,si)
    groups: list[tuple[list[int],bool,int]]=[]
    def chunks(a: list[int],m: int,unanimity_first: bool=False):
        first=True
        while a:
            k=min(len(a),int(rp.integers(2,9)));piece=a[:k];a=a[k:]
            groups.append((piece,unanimity_first and first,m));first=False
    for m in range(3):
        correct=list(map(int,rp.permutation(np.where((modes==m)&(err==0))[0])))
        wrong=list(map(int,rp.permutation(np.where((modes==m)&(err==1))[0])))
        if scenario=='homogeneous_duplicates':
            chunks(correct,m,True);chunks(wrong,m,False)
        elif scenario=='unanimous_mixed':
            nc,ne=round(.6*len(correct)),round(.6*len(wrong))
            groups.append((correct[:nc]+wrong[:ne],True,m));chunks(correct[nc:],m);chunks(wrong[ne:],m)
        elif scenario=='distributed_mixed':
            nc,ne=round(.2*len(correct)),round(.2*len(wrong))
            groups.append((correct[:nc]+wrong[:ne],True,m));c=correct[nc:];e=wrong[ne:]
            k=max(1,min(len(c),len(e),round((len(c)+len(e))/7)))
            bs=[[c[i],e[i]] for i in range(k)]
            for i in list(rp.permutation(c[k:]+e[k:])):bs[int(rp.integers(k))].append(int(i))
            groups.extend((b,False,m) for b in bs)
        elif scenario=='mostly_unique':
            nc,ne=round(.1*len(correct)),round(.1*len(wrong))
            groups.append((correct[:nc]+wrong[:ne],True,m))
            groups.append((correct[nc:2*nc]+wrong[ne:2*ne],False,m))
            groups.extend(([i],False,m) for i in correct[2*nc:]+wrong[2*ne:])
        else:raise ValueError(scenario)
    seen=set();sequences={}
    for ids,unanimity,m in groups:
        assert ids
        if unanimity:s=tuple([f'K{m}']*20)
        else:
            while True:
                c=int(rs.integers(11,20));r1=int(rs.integers(0,21-c));r2=20-c-r1
                s=tuple(map(str,rs.permutation([f'K{m}']*c+[f'K{(m+1)%3}']*r1+[f'K{(m+2)%3}']*r2)))
                if s not in seen:break
        assert s not in seen;seen.add(s)
        for i in ids:assert i not in sequences;sequences[i]=s
    assert len(sequences)==n
    rows=[]
    for i in range(n):
        seq=sequences[i];cnt=[seq.count(f'K{k}') for k in range(3)]
        h=-math.fsum(v/20*math.log(v/20) for v in sorted(cnt) if v)/math.log(3)
        rows.append(enrich({'uid':f's{i:04d}','case_id':f's{i:04d}','model':'synthetic','GT':f'K{gt[i]}',
                     'saved_modal':f'K{modes[i]}','error':int(err[i]),'H_saved':round(h,3),'sequence':'|'.join(seq)},('K0','K1','K2')))
    return rows


